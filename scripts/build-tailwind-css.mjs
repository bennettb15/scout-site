import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedPath = path.join(root, "src", "index.generated.css");

const css = await fs.readFile(generatedPath, "utf8");
if (!css.includes("Generated by scripts/build-tailwind-css.mjs")) {
  throw new Error("src/index.generated.css is missing the generated CSS banner.");
}
if (!css.includes("tailwindcss v4.1.18")) {
  throw new Error("src/index.generated.css does not look like the expected Tailwind output.");
}

console.log(`Verified ${path.relative(root, generatedPath)} (${css.length} bytes)`);
