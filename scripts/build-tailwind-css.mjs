import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "@tailwindcss/postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "src", "index.css");
const outputPath = path.join(root, "src", "index.generated.css");

const source = await fs.readFile(sourcePath, "utf8");
const result = await postcss([tailwindcss()]).process(source, {
  from: sourcePath,
});

const banner = "/* Generated by scripts/build-tailwind-css.mjs. Do not edit directly. */\n";
await fs.writeFile(outputPath, banner + result.css, "utf8");
console.log(`Generated ${path.relative(root, outputPath)} (${result.css.length} bytes)`);
