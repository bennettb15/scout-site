import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "@tailwindcss/postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "src", "index.css");
const generatedPath = path.join(root, "src", "index.generated.css");
const source = await fs.readFile(sourcePath, "utf8");
const result = await postcss([tailwindcss()]).process(source, {
  from: sourcePath,
  to: generatedPath,
});
const banner = "/* Generated by scripts/build-tailwind-css.mjs. Do not edit directly. */\n";
await fs.writeFile(generatedPath, banner + result.css);
console.log(`Generated ${path.relative(root, generatedPath)} (${result.css.length} bytes)`);
